#!/usr/bin/env bash
#
# sync-rea-skill.sh — vendor REA's agent skill into this repo at a pinned tag.
#
# Copies skills/reverse-engineer-anything/ (plus REA's MIT LICENSE) from a local
# clone of github.com/morluto/rea into users/dev/skills/, replacing the previous
# copy. That directory is a gitignored BUILD artifact (`npm run build:cached`
# generates it from .agents/skills; it is what the npm package ships), so the
# clone must be checked out at <tag> and built. Touches only this repo;
# users/install.sh deploys it.
#
# We vendor instead of running `rea setup --skill`, which writes straight into
# ~/.claude/skills (a live symlink into ~/.agents, generated by install.sh).
#
# Usage:
#   scripts/sync-rea-skill.sh [tag] [rea-clone]
#     tag        default: rea-agents-6.9.0
#     rea-clone  default: /srv/dev/repos/rea

set -euo pipefail

tag="${1:-rea-agents-6.9.0}"
clone="${2:-/srv/dev/repos/rea}"
repo_root="$(cd "$(dirname "$0")/.." && pwd)"
dest="$repo_root/users/dev/skills/reverse-engineer-anything"
src="skills/reverse-engineer-anything"

head_tags="$(git -C "$clone" tag --points-at HEAD)"
grep -qxF "$tag" <<<"$head_tags" || {
  echo "$clone HEAD is not at $tag; run: git -C $clone checkout $tag && (cd $clone && npm ci && npm run build:cached)" >&2
  exit 1
}
[ -f "$clone/$src/SKILL.md" ] || {
  echo "$clone/$src missing; build the clone first: (cd $clone && npm run build:cached)" >&2
  exit 1
}

rm -rf "$dest"
mkdir -p "$dest"
cp -a "$clone/$src/." "$dest/"
cp "$clone/LICENSE" "$dest/LICENSE"

echo "vendored $src @ $tag ($(git -C "$clone" rev-parse --short "$tag^{commit}")) -> ${dest#"$repo_root"/}"
echo "update the version noted in users/dev/skills/README.md, then run users/install.sh"
